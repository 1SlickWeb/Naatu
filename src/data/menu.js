export const totalItems = categories.reduce((n, c) => n + c.items.length, 0);

/** Look up a dish by its exact name (used for hand-picked lists). */
export const findItem = (name) => {
  for (const c of categories) {
    const item = c.items.find((i) => i.name === name);
    if (item) return { ...item, category: c.name };
  }
  return null;
};
